import test from 'node:test';
import assert from 'node:assert/strict';
import { requireIsolatedTestDatabase } from '../../scripts/test-database-guard.mjs';
const url=process.env.TEST_DATABASE_URL;
if(url){requireIsolatedTestDatabase(url,process.env.DATABASE_URL);process.env.DATABASE_URL=url;}
const db=url ? await import('../../lib/db/index.js') : null;
test.after(async()=>{if(db)await db.closePgPool();});

test('currency exchange locks one FX snapshot, preserves legacy credits and replays the original result',{skip:!url},async()=>{
  const {allocateUserId}=await import('../../lib/auth/user-id.js');
  const auth=await import('../../lib/repositories/auth.js');
  const {exchangeCoinToCredits,buyVipWithCoin}=await import('../../lib/financial/exchangeService.js');
  const id=await allocateUserId({reserve:(candidate,digits)=>auth.reserveUserId(candidate,digits),findFirstAvailable:digits=>auth.findFirstAvailableUserId(digits),isExhausted:digits=>auth.isUserIdPoolExhausted(digits)});
  await db.execute("INSERT INTO auth_usr.users(id,email,password_hash,password_salt,role,credits,status) VALUES($1,$2,'test','test','user',17,'active')",[id,`${id}@exchange.test`]);
  await db.execute('INSERT INTO ops_bill.currency_wallets(user_id,available_balance) VALUES($1,20)',[id]);
  const fxId=`exchange_fx_${id}`,key=`exchange_${id}`;
  await db.execute("INSERT INTO ai_studio.exchange_rate_snapshots(id,base_currency,quote_currency,rate,source_type,observed_at,expires_at) VALUES($1,'USD','CNY',7,'manual',now(),now()+interval '1 day')",[fxId]);
  const results=await Promise.all(Array.from({length:4},()=>exchangeCoinToCredits({userId:id,coinAmount:1,idempotencyKey:key})));
  assert.equal(results.filter(result=>!result.idempotent).length,1);
  assert.ok(results.every(result=>result.creditsGained===100 && result.creditBalanceAfter===117));
  assert.equal(Number((await db.queryOne('SELECT available_balance FROM ops_bill.currency_wallets WHERE user_id=$1',[id])).available_balance),19);
  const journal=await db.queryMany('SELECT direction,amount FROM ops_bill.currency_journal_entries WHERE transaction_id=$1',[results[0].transactionId]);
  assert.deepEqual(journal.map(row=>[row.direction,Number(row.amount)]).sort(),[['CREDIT',1],['DEBIT',1]]);
  await db.execute('UPDATE ai_studio.exchange_rate_snapshots SET rate=8,expires_at=now()-interval \'1 second\' WHERE id=$1',[fxId]);
  assert.equal((await exchangeCoinToCredits({userId:id,coinAmount:1,idempotencyKey:key})).creditsGained,100);
  await assert.rejects(exchangeCoinToCredits({userId:id,coinAmount:2,idempotencyKey:key}),{code:'EXCHANGE_IDEMPOTENCY_CONFLICT'});
  await assert.rejects(exchangeCoinToCredits({userId:id,coinAmount:1,idempotencyKey:`new_${key}`}),{code:'FX_RATE_UNAVAILABLE'});
  await assert.rejects(exchangeCoinToCredits({userId:id,coinAmount:Infinity,idempotencyKey:`invalid_${key}`}),{code:'EXCHANGE_AMOUNT_INVALID'});
  await db.execute('UPDATE ai_studio.exchange_rate_snapshots SET expires_at=now()+interval \'1 day\' WHERE id=$1',[fxId]);
  const planId=`exchange_plan_${id}`;
  await db.execute("INSERT INTO ops_bill.plans_config(id,name,monthly_cny,monthly_usd,features_json) VALUES($1,'Fixture plan',14,2,$2::jsonb)",[planId,JSON.stringify({features:[],meta:{quotaBase:123}})]);
  const vip=await buyVipWithCoin({userId:id,planId,idempotencyKey:`vip_${key}`});
  assert.equal(vip.subCreditsBonus,123);
  assert.equal((await db.queryOne('SELECT subscription_credits FROM ops_bill.credit_wallets WHERE user_id=$1',[id])).subscription_credits,123);
  assert.equal((await db.queryOne('SELECT credits FROM auth_usr.users WHERE id=$1',[id])).credits,240);
  assert.equal((await buyVipWithCoin({userId:id,planId,idempotencyKey:`vip_${key}`})).transactionId,vip.transactionId);
  await db.execute("UPDATE ops_bill.subscriptions SET current_period_end=now()-interval '1 minute' WHERE user_id=$1",[id]);
  await db.execute("UPDATE ops_bill.credit_wallets SET subscription_expires_at=now()-interval '1 minute' WHERE user_id=$1",[id]);
  await db.execute("UPDATE auth_usr.users SET avatar_url='/branding/favicon.svg' WHERE id=$1",[id]);
  const {getEntitlements}=await import('../../lib/services/billing.js');
  const expired=await getEntitlements(id);
  assert.equal(expired.isPaidSubscription,false);
  assert.equal(expired.planId,'free');
  assert.equal(expired.creditBuckets.totalAvailable,117);
  const {createSession,getUserBySession}=await import('../../lib/services/auth.js');
  const session=await createSession(id);
  const mainUser=await getUserBySession(session.token);
  assert.equal(mainUser.isSubscribed,false);
  const {GET}=await import('../../app/api/canvas/session/route.js');
  const {NextRequest}=await import('next/server.js');
  const canvasResponse=await GET(new NextRequest('https://canvas.supdance.com/api/canvas/session',{headers:{Origin:'https://canvas.supdance.com',Cookie:`ko_session=${session.token}`}}));
  assert.equal(canvasResponse.status,200);
  const canvas=await canvasResponse.json();
  assert.equal(canvas.user.avatar,mainUser.avatar);
  assert.equal(canvas.user.avatar,'/branding/favicon.svg');
  assert.equal(canvas.subscription.isPaid,false);
  assert.equal(canvas.subscription.planId,expired.planId);
  assert.equal(canvas.credits,expired.credits);
  await db.execute('DELETE FROM ai_studio.exchange_rate_snapshots WHERE id=$1',[fxId]);
});
