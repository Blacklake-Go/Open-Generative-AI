/**
 * Auth copy registry and localized navigation routes.
 *
 * Placed in lib/ to adhere to routePolicy ratchets (copyLayer).
 * Fully covers all 6 supported locales: en, zh-CN, zh-TW, ja-JP, ko-KR, es.
 */

export const AUTH_LOCALES = ['en', 'zh-CN', 'zh-TW', 'ja-JP', 'ko-KR', 'es'];

export const AUTH_LOCALE_CONFIGS = {
  en: { code: 'en', label: 'English', rootPath: '' },
  'zh-CN': { code: 'zh-CN', label: '简体中文', rootPath: '/zh' },
  'zh-TW': { code: 'zh-TW', label: '繁體中文', rootPath: '/zh-TW' },
  'ja-JP': { code: 'ja-JP', label: '日本語', rootPath: '/ja-JP' },
  'ko-KR': { code: 'ko-KR', label: '한국어', rootPath: '/ko-KR' },
  es: { code: 'es', label: 'Español', rootPath: '/es' },
};

export function normalizeAuthLocale(locale) {
  const raw = String(locale || '').trim();
  if (AUTH_LOCALE_CONFIGS[raw]) return raw;
  const lower = raw.toLowerCase();
  if (lower === 'zh' || lower === 'zh-cn' || lower === 'zh_cn') return 'zh-CN';
  if (lower === 'zh-tw' || lower === 'zh_tw' || lower === 'zh-hk') return 'zh-TW';
  if (lower === 'ja' || lower.startsWith('ja-')) return 'ja-JP';
  if (lower === 'ko' || lower.startsWith('ko-')) return 'ko-KR';
  if (lower === 'es' || lower.startsWith('es-')) return 'es';
  if (lower === 'en' || lower.startsWith('en-')) return 'en';
  return 'en';
}

export function getAuthRoutes(locale = 'zh-CN', currentPath = '') {
  const normalized = normalizeAuthLocale(locale);
  const config = AUTH_LOCALE_CONFIGS[normalized] || AUTH_LOCALE_CONFIGS.en;
  const prefix = config.rootPath;
  const isChinese = normalized === 'zh-CN' || normalized === 'zh-TW';

  // Strip any existing locale prefix from currentPath to obtain base route
  const cleanPath = (currentPath || '/login')
    .replace(/^\/(?:zh-TW|ja-JP|ko-KR|zh|es)(?=\/|$)/, '') || '/login';

  const localeOptions = AUTH_LOCALES.map((code) => {
    const itemConfig = AUTH_LOCALE_CONFIGS[code];
    return {
      code,
      label: itemConfig.label,
      active: code === normalized,
      url: `${itemConfig.rootPath}${cleanPath}`,
    };
  });

  return {
    locale: normalized,
    isChinese,
    prefix,
    studioUrl: `${prefix}/studio`,
    loginUrl: `${prefix}/login`,
    registerUrl: `${prefix}/register`,
    forgotPasswordUrl: `${prefix}/forgot-password`,
    changePasswordUrl: `${prefix}/change-password`,
    profileUrl: `${prefix}/profile`,
    termsUrl: `${prefix}/terms`,
    privacyUrl: `${prefix}/privacy`,
    localeOptions,
    // Backward compatibility for existing simple toggles
    switchLocaleUrl: normalized === 'zh-CN' ? cleanPath : `/zh${cleanPath}`,
    switchLocaleLabel: normalized === 'zh-CN' ? 'English' : '简体中文',
  };
}

