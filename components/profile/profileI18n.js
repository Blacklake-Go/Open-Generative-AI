export function getProfileStrings(locale) {
  const norm = normalizeLocale(locale);
  return PROFILE_I18N[norm] || PROFILE_I18N.en;
}

export function useProfileLocale(explicitLocale = null) {
  return resolveClientLocale({
    explicit: explicitLocale,
    pathname: typeof window !== 'undefined' ? window.location.pathname : '',
    search: typeof window !== 'undefined' ? window.location.search : '',
    userLocale: typeof document !== 'undefined' ? document.cookie.match(/(?:^|;\s*)(?:NEXT_LOCALE|locale)=([^;]+)/)?.[1] : null,
  });
}
